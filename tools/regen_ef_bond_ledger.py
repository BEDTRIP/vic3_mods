OUT_MAT = os.path.join(HOT, "scripted_effects", "zz_ef_bond_maturity_no_payout.txt")
SLOTS = range(1, 11)
HEAD = "# GENERATED by tools/regen_ef_bond_ledger.py -- do not edit by hand.\n"


def match(text, i):
    d = 0
    for j in range(i, len(text)):
        d += {"{": 1, "}": -1}.get(text[j], 0)
        if d == 0:
            return j
    raise AssertionError


def block(t, name):
    m = re.search(rf"^{name} = \{{", t, re.M)
    assert m, f"{name} not found"
    i = t.index("{", m.start())
    return t[i + 1:match(t, i)]


def slot(n):
    return f"""
# slot {n}: E&F's ai_buy_bond_{n}_on / ai_seller_country_general_{n} / ai_total_bond_value_{n}
zz_ef_bl_slot_{n} = {{
	if = {{
		limit = {{
			has_variable = ai_buy_bond_{n}_on
			var:ai_buy_bond_{n}_on = 1
			NOT = {{ has_variable = zz_ef_bh_{n} }}
			has_variable = ai_seller_country_general_{n}
			has_variable = ai_total_bond_value_{n}
			exists = var:ai_seller_country_general_{n}
			var:ai_seller_country_general_{n} = {{ is_country_type = recognized }}
		}}
		set_variable = {{ name = zz_ef_bs_{n} value = var:ai_seller_country_general_{n} }}
		set_variable = {{ name = zz_ef_bh_{n} value = var:ai_total_bond_value_{n} }}
		zz_ef_bl_register = {{ N = {n} }}
	}}
	else_if = {{
		limit = {{
			has_variable = zz_ef_bh_{n}
			has_variable = ai_buy_bond_{n}_on
			var:ai_buy_bond_{n}_on = 1
			has_variable = zz_ef_bs_{n}
			exists = var:zz_ef_bs_{n}
		}}
		zz_ef_bl_hold = {{ N = {n} }}
	}}
	else_if = {{
		limit = {{ has_variable = zz_ef_bh_{n} }}
		zz_ef_bl_end = {{ N = {n} }}
	}}
}}
"""


