def maturity():
    t = open(SRC, encoding="utf-8-sig").read()
    out = [HEAD, "# В5.5 (5.10): E&F's bond maturity without its payout from nobody; the buyer's income modifier off -- see\n"
           "# tools/regen_ef_bond_ledger.py. !! MAINTENANCE !! Key-level REPLACE_OR_CREATE: regenerate after an E&F update.\n"]
    for n in SLOTS:
        body = block(t, f"ai_bond_maturity_{n}")
        pat = re.compile(r"\n[ \t]*if = \{\s*limit = \{\s*ai_no_longer_exists_%d = 1\s*\}\s*add_treasury = \{\s*add = "
                         r"var:ai_total_bond_value_%d\s*\}\s*\}" % (n, n))
        body, k = pat.subn("\n\t\t# В5.5: the payout from nobody removed -- the ledger buys the part back", body)
        assert k == 1, f"ai_bond_maturity_{n}: payout {k}"
        assert "add_treasury" not in body
        out.append(f"\nREPLACE_OR_CREATE:ai_bond_maturity_{n} = {{{body}}}\n")
    body = block(t, "interest_per_month_from_foreign_debt_investment")
    assert "add_modifier" in body and "interest_from_foreign_debt_investment" in body, "E&F's interest effect changed"
    out.append("\nREPLACE_OR_CREATE:interest_per_month_from_foreign_debt_investment = {\n"
               "\tremove_modifier = interest_from_foreign_debt_investment\n}\n")
    return "".join(out)


def main():
    outs = [(OUT_LEDGER, ledger()), (OUT_MAT, maturity()),
            (os.path.join(HOT, "script_values", "zz_ef_bond_ledger_values.txt"), values())]
    bad = 0
    for path, text in outs:
        assert text.count("{") == text.count("}"), path
        if "--check" in sys.argv:
            cur = open(path, encoding="utf-8-sig").read() if os.path.exists(path) else ""
            print("ok" if cur == text else "DIFFERS", path)
            bad += cur != text
            continue
        with open(path, "w", encoding="utf-8-sig", newline="\n") as f:
            f.write(text)
        print("ok", path)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
