# Ranks that lose TGR's state_export_advantage_mult / state_import_advantage_mult.
EXPORT_IMPORT_RANKS = [
    "major_power", "unrecognized_major_power", "minor_power",
    "unrecognized_regional_power", "insignificant_power", "unrecognized_power",
]
# Ranks where soft_pop still carries a vanilla-style country_loan_interest_rate_mult
# that the loan-rank decision (report section 12) says to comment out.
LOAN_RANKS = [
    "great_power", "major_power", "insignificant_power",
    "unrecognized_major_power", "unrecognized_regional_power", "unrecognized_power",
]
# Ranks that get TGR's new country_construction_add field.
CONSTRUCTION_RANKS = ["great_power", "major_power"]

ALL_RANKS = [
    "great_power", "major_power", "minor_power", "insignificant_power",
    "unrecognized_major_power", "unrecognized_regional_power", "unrecognized_power",
]


def build_country_ranks():
    sp_text = V.read(os.path.join(SOFT_POP, "common/country_ranks/MoG_SPA_country_ranks.txt"))
    tgr_trade_text = V.read(os.path.join(TGR, "common/country_ranks/TGR_TRADE_country_ranks.txt"))
    tgr_pol_text = V.read(os.path.join(TGR, "common/country_ranks/TGR_POLITICS_country_ranks.txt"))

    records = []
    for rank in ALL_RANKS:
        _, sp_body = V.entry(sp_text, rank, "TRY_REPLACE:")
        mod = V.sub(sp_body, "modifier")
        assert mod is not None, f"{rank}: soft_pop record has no modifier block -- re-check GR.7a"
        new_mod = mod

        if rank in LOAN_RANKS:
            m = re.search(r'\n([ \t]*)country_loan_interest_rate_mult\s*=\s*(-?[\d.]+)[^\n]*', new_mod)
            assert m, f"{rank}: expected country_loan_interest_rate_mult in soft_pop's modifier -- re-check GR.7a"
            indent = m.group(1)
            note = (f"\n{indent}# country_loan_interest_rate_mult = {m.group(2)}  restored to a comment on purpose --"
                    f"\n{indent}# decision 27.08.2026 (GR.7a): TGR's loan system drops rank-dependent interest"
                    f"\n{indent}# entirely, and that is followed here rather than Grey's vanilla-style value.")
            new_mod = new_mod[:m.start()] + note + new_mod[m.end():]

        extra_fields = []
        if rank in EXPORT_IMPORT_RANKS:
            _, tgr_body = V.entry(tgr_trade_text, rank, "INJECT:")
            tgr_mod = V.sub(tgr_body, "modifier")
            assert tgr_mod is not None, f"{rank}: TGR_TRADE_country_ranks.txt no longer INJECTs a modifier -- re-check GR.7a"
            fields = re.findall(r'(state_(?:export|import)_advantage_mult\s*=\s*-?[\d.]+)', tgr_mod)
            assert len(fields) == 2, f"{rank}: expected 2 TGR advantage fields, got {fields} -- re-check GR.7a"
            extra_fields += [f + "  # TGR, restored" for f in fields]

        if rank in CONSTRUCTION_RANKS:
            _, tgr_pol_body = V.entry(tgr_pol_text, rank, "REPLACE_OR_CREATE:")
            tgr_pol_mod = V.sub(tgr_pol_body, "modifier")
            assert tgr_pol_mod is not None
            m = re.search(r'country_construction_add\s*=\s*\d+', tgr_pol_mod)
            assert m, f"{rank}: TGR no longer adds country_construction_add -- re-check GR.7a"
            extra_fields.append(m.group(0) + "  # TGR, field didn't exist before")

        if extra_fields:
            close_idx = new_mod.rstrip().rfind('}')
            assert close_idx != -1
            new_mod = new_mod[:close_idx].rstrip() + "\n\t\t" + "\n\t\t".join(extra_fields) + "\n\t}"

        new_body = V.replace_sub(sp_body, "modifier", new_mod)
        records.append(f"REPLACE_OR_CREATE:{rank} = {{{new_body}}}")

    write(
        "common/country_ranks/zz_greys_tgr_country_ranks.txt",
        "\n\n".join(records),
        "restore TGR's trade-advantage and construction fields on seven ranks; drop rank-dependent loan interest per the loan decision",
        "_grey_soft_pop's TRY_REPLACE (matches current 1.13 vanilla, see TGR.1) restates every rank's "
        "modifier block whole, dropping TGR's state_export_advantage_mult/state_import_advantage_mult "
        "INJECT on six ranks and TGR's new country_construction_add on great_power/major_power -- both "
        "restored here, read live from TGR's own files. country_loan_interest_rate_mult is commented "
        "out wherever soft_pop carries it: decision 27.08.2026 (GR.7a) was to follow TGR's own design, "
        "which drops rank-dependent loan interest on purpose as part of its separate loan system, rather "
        "than keep Grey's vanilla-style value. decentralized_power is untouched by either side, not "
        "included. !! MAINTENANCE !! if soft_pop ever stops carrying country_loan_interest_rate_mult on "
        "one of these ranks, or TGR's advantage/construction values change, this generator's asserts will "
        "fail loudly -- re-run and re-check rather than editing the output by hand."
    )


