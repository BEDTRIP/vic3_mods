CITIZENSHIP_LAWS = [
    "law_ethnostate", "law_national_supremacy", "law_racial_segregation", "law_cultural_exclusion",
]


def build_citizenship_laws():
    tgr_text = V.read(os.path.join(TGR, "common/laws/TGR_POLITICS_citizenship.txt"))
    sp_text = V.read(os.path.join(SOFT_POP, "common/laws/zMoG_SPA_citizenship.txt"))

    records = []
    for law in CITIZENSHIP_LAWS:
        _, tgr_body = V.entry(tgr_text, law, "INJECT:")
        tgr_mod = V.sub(tgr_body, "acceptance_modifier")
        assert tgr_mod is not None, f"{law}: TGR no longer INJECTs acceptance_modifier -- re-check GR.7b"
        m = re.search(r'country_political_strength_full_acceptance_mult\s*=\s*(-?[\d.]+)', tgr_mod)
        assert m, f"{law}: TGR's acceptance_modifier lost country_political_strength_full_acceptance_mult -- re-check GR.7b"
        tgr_value = float(m.group(1))
        assert tgr_value < 0, f"{law}: expected TGR's value to be negative (a counterweight), got {tgr_value}"

        _, sp_body = V.entry(sp_text, law, "TRY_REPLACE:")
        sp_mod = V.sub(sp_body, "acceptance_modifier")
        assert sp_mod is not None, f"{law}: soft_pop has no acceptance_modifier -- re-check GR.7b"
        sm = re.search(r'country_political_strength_full_acceptance_mult\s*=\s*(-?[\d.]+)', sp_mod)
        assert sm, f"{law}: soft_pop's acceptance_modifier lost country_political_strength_full_acceptance_mult -- re-check GR.7b"
        sp_value = float(sm.group(1))
        assert abs(sp_value + tgr_value) < 1e-9, (
            f"{law}: soft_pop's {sp_value} and TGR's {tgr_value} no longer net to zero -- "
            f"this is no longer a straight counterweight restore, re-check GR.7b before writing")

        records.append(
            f"INJECT:{law} = {{\n\tacceptance_modifier = {{\n\t\tcountry_political_strength_full_acceptance_mult = {m.group(1)}\n\t}}\n}}"
        )

    write(
        "common/laws/zz_greys_tgr_citizenship.txt",
        "\n\n".join(records),
        "re-issue TGR's acceptance-mult counterweight on four citizenship laws after Grey's later TRY_REPLACE",
        "vanilla gives country_political_strength_full_acceptance_mult = 0.25/0.20/0.1/0.1 on these four "
        "laws; TGR INJECTs the same numbers negated to net the bonus to zero. _grey_soft_pop's later "
        "TRY_REPLACE restates the vanilla (positive) values, and a modifier block's repeated keys sum -- "
        "so TGR's INJECT would need to land on top of a body that still carries the vanilla value to work, "
        "and Grey's body does, so simply re-issuing TGR's own INJECT after the whole Grey's pack nets back "
        "to zero exactly (rules file, section 1: 'counterweight with the opposite sign gets silently "
        "resurrected'). !! MAINTENANCE !! this only works because Grey's value still equals vanilla -- if "
        "_grey_soft_pop ever changes these four numbers on purpose, this stops being a restore and becomes "
        "a balance decision; the generator's assert catches exactly that."
    )


