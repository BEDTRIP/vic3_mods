def _define(text: str, group: str, key: str) -> str:
    _, body = V.entry(text, group)
    m = re.search(r'(?m)^\s*' + re.escape(key) + r'\s*=\s*(-?[\d.]+)', body)
    assert m, f"{group}.{key} not found -- re-check GR.7c"
    return m.group(1)


def build_defines():
    tgr_trade = V.read(os.path.join(TGR, "common/defines/TGR_TRADE_defines.txt"))
    tgr_pops = V.read(os.path.join(TGR, "common/defines/TGR_POPS_defines.txt"))
    sea = V.read(os.path.join(SOFT_ECON, "common/defines/zzz_MoG_SEA_def.txt"))
    spa = V.read(os.path.join(SOFT_POP, "common/defines/zzz_MoG_SPA_def.txt"))

    # Sanity: Grey's currently just restates vanilla on all four -- if that ever
    # stops being true, this is a balance decision, not a restore.
    grey_hq = _define(sea, "NEconomy", "COMPANY_MINIMUM_LEVELS_PER_HQ")
    grey_downsize = _define(sea, "NEconomy", "AUTO_DOWNSIZE_BUILDING_MIN_UNUSED_TRADE_CAPACITY")
    grey_base = _define(spa, "NPops", "MAX_DEMAND_ADJUSTMENT_BASE_AMOUNT")
    grey_scaled = _define(spa, "NPops", "MAX_DEMAND_ADJUSTMENT_SCALED_AMOUNT")
    assert grey_hq == "5", f"soft_econ's COMPANY_MINIMUM_LEVELS_PER_HQ changed to {grey_hq} -- re-check GR.7c"
    assert grey_downsize == "20", f"soft_econ's AUTO_DOWNSIZE_BUILDING_MIN_UNUSED_TRADE_CAPACITY changed to {grey_downsize} -- re-check GR.7c"
    assert grey_base == "0.01", f"soft_pop's MAX_DEMAND_ADJUSTMENT_BASE_AMOUNT changed to {grey_base} -- re-check GR.7c"
    assert grey_scaled == "0.09", f"soft_pop's MAX_DEMAND_ADJUSTMENT_SCALED_AMOUNT changed to {grey_scaled} -- re-check GR.7c"

    tgr_hq = _define(tgr_trade, "NEconomy", "COMPANY_MINIMUM_LEVELS_PER_HQ")
    tgr_downsize = _define(tgr_trade, "NEconomy", "AUTO_DOWNSIZE_BUILDING_MIN_UNUSED_TRADE_CAPACITY")
    tgr_base = _define(tgr_pops, "NPops", "MAX_DEMAND_ADJUSTMENT_BASE_AMOUNT")
    tgr_scaled = _define(tgr_pops, "NPops", "MAX_DEMAND_ADJUSTMENT_SCALED_AMOUNT")

    text = (
        "NEconomy = {\n"
        f"\tCOMPANY_MINIMUM_LEVELS_PER_HQ = {tgr_hq}\n"
        f"\tAUTO_DOWNSIZE_BUILDING_MIN_UNUSED_TRADE_CAPACITY = {tgr_downsize}\n"
        "}\n\n"
        "NPops = {\n"
        f"\tMAX_DEMAND_ADJUSTMENT_BASE_AMOUNT = {tgr_base}\n"
        f"\tMAX_DEMAND_ADJUSTMENT_SCALED_AMOUNT = {tgr_scaled}\n"
        "}"
    )
    write(
        "common/defines/zz_greys_tgr_defines.txt",
        text,
        "restore four defines TGR deliberately changed and Grey's silently reverts to vanilla",
        "defines merge per key, last mod loaded wins (rules file, section 1). On these four keys "
        "_grey_soft_econ / _grey_soft_pop just restate the vanilla default -- not a decision, a "
        "no-op -- while TGR made a deliberate change on each. Loading later, Grey's plain vanilla "
        "restatement wins and TGR's choice is gone with nothing in error.log. PRICE_RANGE and "
        "BUY_SELL_DIFF_AT_MAX_FACTOR are NOT here -- decision point #3, soft_econ's own values (0.9 / 3) "
        "were kept on purpose, see the plan and report section 5."
    )


