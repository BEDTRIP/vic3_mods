def build_base_values():
    """VC REPLACE_OR_CREATEs base_values with a 103-line body and eats three TGR
    INJECTs. Re-issuing the same INJECTs after VC restores them exactly: repeated
    keys inside a modifier block ADD, so the result is "VC value + TGR delta" --
    the same delta TGR applies to vanilla. Do not try to write final numbers here;
    TGR's figures are addends, not totals."""
    inner, sources = [], 0
    for name in sorted(os.listdir(os.path.join(TGR, "common/static_modifiers"))):
        body = record(os.path.join(TGR, "common/static_modifiers", name), "base_values")
        if not body:
            continue
        sources += 1
        inner.append(f"\t# from TheGreatRevision/common/static_modifiers/{name}")
        for line in body[1:-1]:               # drop TGR's own `base_values = {` and `}`
            if line.strip():
                inner.append(line)
        inner.append("")
    assert sources == 3, f"expected 3 TGR base_values injects, got {sources}"
    # One INJECT block, not three: TGR splits them across three files only because
    # they belong to three of his subsystems. Their keys are disjoint, and repeated
    # keys in a modifier block add anyway, so folding them into one block is
    # equivalent and avoids re-declaring the same key three times in one file.
    out = ["INJECT:base_values = {", *inner, "}"]
    write("common/static_modifiers/zz_vc_tgr_base_values.txt", "\n".join(out),
          "static modifier base_values",
          "VC's REPLACE_OR_CREATE:base_values wipes TGR's three INJECTs "
          "(loan interest, bureaucracy/authority/influence, officer and soldier\n"
          "#   political strength, company construction efficiency, trade advantage). "
          "Silent: no log line.")


