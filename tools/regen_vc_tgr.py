"""
regen_vc_tgr.py -- builds the TGR x VC compatch in `_vc/tgr+vc done`.

The pair: The Great Revision loads early, Victorian Century loads last, and VC
wins every hard overwrite -- 172 shared keys and 14 shared file paths. Full
analysis: `_vc/tgr+vc done/conflicts_tgr_vs_vc_report.md`.

Vanilla is the common ancestor of both mods for every record here, so the merge
is three-way (see vic3merge3.py) rather than hand-written bodies. What the two
authors did to different lines is kept from both; what they did to the SAME lines
is a conflict, and every conflict is either resolved by a declared winner below
or printed for a human. Nothing is resolved silently.

Decisions taken 25.08.2026 (recorded in `План проекта.md`, fork 8):
  * buy_packages -- VC's numbers are the base, TGR's own headline multipliers
    (+25% from wealth_10, +50% from wealth_21 on basic_food / luxury_food /
    luxury_drinks) are re-applied on top. Both economies survive.
  * German unification -- stitched: VC's state list and Frankfurt gate, TGR's
    buttons, Bismarck pulse and 21-state annexation.
  * Parties -- VC wins the "three or more members" multiplier; TGR's other two
    adjustments (no marginal-IG gate, +50 for the party's natural IG) are kept.

Usage:
    python3 regen_vc_tgr.py            # write the compatch
    python3 regen_vc_tgr.py --check    # report only, exit 1 if sources drifted
"""

