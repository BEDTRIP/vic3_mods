FIELD_RE = re.compile(r"^(\s*)(weight|max_supply_share|min_supply_share|default"
                      r"|obsession_demand_min|obsession_demand_mult"
                      r"|prestige_goods_demand_increase)(\s*=\s*)([0-9.]+)(.*)$")
GOODS_RE = re.compile(r"^\s*goods\s*=\s*([A-Za-z0-9_]+)")


def _entries(lines):
    """Split a popneed body into (head, [entry_blocks]) keyed by goods name."""
    head, entries, cur, name = [], [], None, None
    depth = 0
    for line in lines:
        code = line.split("#", 1)[0]
        if cur is None and re.match(r"^\s*entry\s*=\s*\{", code):
            cur, name, depth = [line], None, code.count("{") - code.count("}")
            continue
        if cur is None:
            head.append(line)
            continue
        cur.append(line)
        m = GOODS_RE.match(code)
        if m:
            name = m.group(1)
        depth += code.count("{") - code.count("}")
        if depth <= 0:
            entries.append((name, cur))
            cur = None
    if cur is not None:
        entries.append((name, cur))
    return head, entries


def _fields(block):
    out = {}
    for line in block:
        m = FIELD_RE.match(line.split("#", 1)[0])
        if m:
            out[m.group(2)] = m.group(4)
    return out


def build_pop_needs(report):
    """Field-level merge, not line-level, because the two designs are orthogonal
    per field and a line diff would cluster them:

      * TGR reworks `max_supply_share` / `min_supply_share` -- narrow the ceiling
        (0.75-1.0 -> 0.3-0.5), raise the floor (0.0 -> 0.2-0.3). That is his
        "pops must consume a mix" system, and it is the whole point of the record.
      * VC reworks `weight` -- how much a good counts inside the need.

    Rule: supply shares from TGR, weight from VC where VC moved it off vanilla,
    otherwise from TGR. Entries only TGR has (he adds `fish` to luxury food) are
    carried over."""
    out = []
    for key in POPNEEDS:
        base = record(find_file(VAN, "common/pop_needs", key), key)
        a = record(find_file(TGR, "common/pop_needs", key), key)
        b = record(find_file(VC, "common/pop_needs", key), key)
        vh, ve = _entries(base)
        ah, ae = _entries(a)
        bh, be = _entries(b)
        av = {n: _fields(bl) for n, bl in ae}
        bv = {n: _fields(bl) for n, bl in be}
        vv = {n: _fields(bl) for n, bl in ve}
        merged = list(bh)                       # head: VC's (default, obsession_*, ...)
        # head fields TGR moved and VC did not
        for i, line in enumerate(merged):
            m = FIELD_RE.match(line.split("#", 1)[0])
            if not m:
                continue
            f = m.group(2)
            hv, ha_, hb = (_fields(vh).get(f), _fields(ah).get(f), _fields(bh).get(f))
            if ha_ is not None and ha_ != hv and hb == hv:
                merged[i] = f"{m.group(1)}{f}{m.group(3)}{ha_}\t# TGR"
        body = []
        for name, block in be:                  # entries in VC's order
            new = []
            for line in block:
                m = FIELD_RE.match(line.split("#", 1)[0])
                if not m:
                    new.append(line)
                    continue
                f = m.group(2)
                van_v = vv.get(name, {}).get(f)
                tgr_v = av.get(name, {}).get(f)
                vc_v = m.group(4)
                if f in ("max_supply_share", "min_supply_share") and tgr_v is not None:
                    pick, who = tgr_v, "TGR"
                elif vc_v != van_v or tgr_v is None or tgr_v == van_v:
                    pick, who = vc_v, "VC"
                else:
                    pick, who = tgr_v, "TGR"
                mark = "" if pick == vc_v and who == "VC" else f"\t# {who} ({van_v} vanilla)"
                new.append(f"{m.group(1)}{f}{m.group(3)}{pick}{mark}")
            body.extend(new)
        for name, block in ae:                  # entries only TGR has
            if name not in bv:
                body.append("\t# entry added by TGR, absent from vanilla and VC")
                body.extend(block)
                report.append((f"common/pop_needs/{key}", -1, -1,
                               [f"extra entry: {name}"], ["(absent)"], "a"))
        out.append("REPLACE_OR_CREATE:" + "\n".join(merged[:-1] + body + [merged[-1]]))
        out.append("")
    write("common/pop_needs/zz_vc_tgr_pop_needs.txt", "\n".join(out),
          "the eight contested pop needs",
          "both REPLACE_OR_CREATE, VC wins, and TGR's whole supply-share rework "
          "disappears silently.")


