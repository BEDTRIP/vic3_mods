MULT_GOODS = ("popneed_basic_food", "popneed_luxury_food", "popneed_luxury_drinks")


def _packages(path):
    lines = read_lines(path)
    out, cur, name = {}, None, None
    depth = 0
    for line in lines:
        code = line.split("#", 1)[0]
        m = re.match(r"^﻿?(?:REPLACE_OR_CREATE:)?(wealth_\d+)\s*=\s*\{", code)
        if m and cur is None:
            name, cur, depth = m.group(1), [line], code.count("{") - code.count("}")
            continue
        if cur is None:
            continue
        cur.append(line)
        depth += code.count("{") - code.count("}")
        if depth <= 0:
            out[name] = cur
            cur = None
    return out


def build_buy_packages(report):
    """99 packages, and the loudest fork in the pair.

    TGR ships his rebalance at the vanilla path `common/buy_packages/00_buy_packages.txt`
    with bare bodies; VC REPLACE_OR_CREATEs all 99 from `joi_buy_packages.txt` and
    takes the lot.

    The two share a non-vanilla base (wealth_7 basic_food: vanilla 115, both 118),
    so most cells are not actually in dispute. Decision 25.08.2026: VC's numbers
    are the base, and TGR's own headline multipliers -- stated in the header of his
    file, +25% from wealth_10 and +50% from wealth_21 on basic food, luxury food and
    luxury drinks -- are re-applied on top. Both rebalances then live: VC keeps its
    services / leisure / communication curve, TGR keeps "the rich eat more".

    Where only TGR moved a good off vanilla (intoxicants and stimulants low down the
    ladder), TGR's number is taken as is.

    The multiplier is derived, not copied, so it stays right when VC updates its
    numbers. The run prints how far the derived value lands from TGR's own -- a
    residual above a rounding step means TGR changed his formula and the header
    has to be re-read."""
    van = _packages(os.path.join(VAN, "common/buy_packages/00_buy_packages.txt"))
    tgr = _packages(os.path.join(TGR, "common/buy_packages/00_buy_packages.txt"))
    vc = _packages(os.path.join(VC, "common/buy_packages/joi_buy_packages.txt"))
    assert len(van) == len(tgr) == len(vc) == 99, (len(van), len(tgr), len(vc))

    def values(block):
        out = {}
        for line in block:
            m = re.match(r"^\s*(popneed_[a-z_]+)\s*=\s*([0-9]+)", line.split("#", 1)[0])
            if m:
                out[m.group(1)] = int(m.group(2))
        return out

    out, residuals, taken_tgr = [], [], 0
    for n in range(1, 100):
        key = f"wealth_{n}"
        mult = 1.5 if n >= 21 else (1.25 if n >= 10 else 1.0)
        v, t, c = values(van[key]), values(tgr[key]), values(vc[key])
        new = []
        for line in vc[key]:
            m = re.match(r"^(\s*)(popneed_[a-z_]+)(\s*=\s*)([0-9]+)(.*)$", line.split("#", 1)[0])
            if not m:
                new.append(line)
                continue
            good = m.group(2)
            val = int(m.group(4))
            note = ""
            tgr_moved = good in t and good in v and t[good] != v[good]
            vc_moved = c.get(good) != v.get(good)
            if tgr_moved and not vc_moved:
                # Only TGR touched this cell -- his number already carries whatever
                # multiplier he meant. Re-deriving it from vanilla would be worse,
                # not better: his luxury-food ladder is not vanilla x1.25.
                note = f"\t# TGR ({v[good]} vanilla)"
                val = t[good]
                taken_tgr += 1
            elif tgr_moved and vc_moved and good in MULT_GOODS and mult != 1.0:
                # Both moved it, and it is one of the three needs TGR's own header
                # names. Derive from VC's number so the multiplier follows VC if VC
                # rebalances again.
                scaled = int(round(val * mult))
                residuals.append((key, good, t[good], scaled))
                note = f"\t# {val} x{mult} TGR"
                val = scaled
            new.append(f"{m.group(1)}{good}{m.group(3)}{val}{note}")
        # Strip VC's own prefix first. Gluing one on top of another produces
        # REPLACE_OR_CREATE:REPLACE_OR_CREATE:wealth_1 and the record silently
        # does not load -- no error, the packages just stay vanilla.
        new[0] = "REPLACE_OR_CREATE:" + re.sub(r"^﻿?(?:[A-Z_]+:)?", "", new[0])
        out.extend(new)
        out.append("")
    off = [r for r in residuals if abs(r[2] - r[3]) > 1]
    print(f"  buy_packages: {len(residuals)} multiplied cells, {len(off)} off TGR's own "
          f"value by more than a rounding step; {taken_tgr} cells taken from TGR outright")
    for key, good, tgr_v, ours in off[:12]:
        print(f"    {key:>10} {good:<26} TGR={tgr_v:<5} ours={ours}")
    if off:
        report.append(("common/buy_packages", -1, -1,
                       [f"{len(off)} cells differ from TGR's own numbers by >1"],
                       ["VC base x TGR multiplier"], "b"))
    write("common/buy_packages/zz_vc_tgr_buy_packages.txt", "\n".join(out),
          "all 99 wealth_* buy packages",
          "VC REPLACE_OR_CREATEs all 99 and TGR's whole consumption rebalance "
          "disappears. See the decision above.")


