def build_on_action():
    text = ("on_yearly_pulse_country = {\n"
            "\ton_actions = {\n"
            "\t\tzz_llwa_ef_on_yearly_pulse_country\n"
            "\t}\n"
            "}\n\n"
            "zz_llwa_ef_on_yearly_pulse_country = {\n"
            "\teffect = {\n"
            "\t\tllwa_private_ownership_production_stocks = yes\n"
            "\t}\n"
            "}")
    write("common/on_actions/zz_llwa_ef_on_actions.txt",
          text,
          "hook the LLWA private-ownership stock switch into the yearly pulse",
          "on_actions are additive across mods -- this overrides nothing from E&F, "
          "Morgenroete's own compatch, or anyone else also appending to "
          "on_yearly_pulse_country.")


def build_history_init():
    text = ("GLOBAL = {\n"
            "\tevery_country = {\n"
            "\t\tllwa_private_ownership_production_stocks = yes\n"
            "\t}\n"
            "}")
    write("common/history/global/zz_llwa_ef_stocks_init.txt",
          text,
          "initialise the stock production methods at game start",
          "on_yearly_pulse_country only fires a year after the start, so LLWA's "
          "buildings would sit on \"No ... Stock\" for the whole first year even "
          "when private ownership is already past half. Same fix E&F uses for its "
          "own buildings and ef+morg done uses for Morgenroete's. GLOBAL blocks "
          "stack across mods -- additive, overrides nothing.")


def self_check() -> int:
    bad = 0
    seen: dict[tuple[str, str], str] = {}
    for rel, blob in sorted(WRITTEN.items()):
        text = blob.decode("utf-8-sig")
        if brace_balance(text) != 0:
            print(f"  FAIL {rel}: brace balance {brace_balance(text)}")
            bad += 1
        if needs_bom(text) and not blob.startswith(b"\xef\xbb\xbf"):
            print(f"  FAIL {rel}: non-ASCII outside a comment, needs a BOM")
            bad += 1
        doubled = re.findall(r"^[A-Z_]+:[A-Z_]+:", text, re.M)
        if doubled:
            print(f"  FAIL {rel}: {len(doubled)} doubled prefix(es), e.g. {doubled[0]}")
            bad += 1
        category = os.path.dirname(rel)
        depth = 0
        for raw in text.split("\n"):
            code = raw.split("#", 1)[0]
            if depth == 0:
                m = re.match(r"^﻿?([A-Z_]+:)?([A-Za-z0-9_.\-]+)\s*=\s*\{", code)
                if m and (m.group(1) or "").rstrip(":") in ("INJECT", "TRY_INJECT"):
                    m = None
                if m and m.group(2) not in ("COUNTRIES", "GLOBAL", "BUILDINGS", "POPS"):
                    where = (category, m.group(2))
                    if where in seen:
                        print(f"  FAIL duplicate key {m.group(2)} in {category}: "
                              f"{seen[where]} and {rel}")
                        bad += 1
                    seen[where] = rel
            depth += code.count("{") - code.count("}")
    print(f"  self-check: {len(WRITTEN)} files, {len(seen)} top-level keys, "
          f"{bad} problem(s)")
    return bad


def main() -> int:
    global CHECK_ONLY
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="report only, do not write")
    args = ap.parse_args()
    CHECK_ONLY = args.check

    print(f"regen_llwa_ef.py -> {OUT}")
    verify_sources()
    for name, fn in (
        ("buildings inject", build_buildings_inject),
        ("switch effect", build_switch_effect),
        ("on_action", build_on_action),
        ("history init", build_history_init),
    ):
        print(f"[{name}]")
        fn()

    print()
    bad = self_check()
    if args.check:
        drifted = [r for r, blob in WRITTEN.items()
                   if (open(os.path.join(OUT, r), "rb").read()
                       if os.path.isfile(os.path.join(OUT, r)) else None) != blob]
        if drifted:
            print(f"\n{len(drifted)} file(s) on disk no longer match the sources:")
            for r in drifted:
                print("  " + r)
            return 1
        print("\nall files match the current LLWA / E&F sources")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
