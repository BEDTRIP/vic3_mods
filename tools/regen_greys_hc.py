def build_decree():
    vtext = V.read(os.path.join(VANILLA, "common/decrees/00_decree.txt"))
    _, vbody = V.entry(vtext, "decree_greener_grass_campaign")
    hctext = V.read(os.path.join(HC, "common/decrees/usfp_decrees_overwrite.txt"))
    _, hcbody = V.entry(hctext, "decree_greener_grass_campaign", "REPLACE:")
    sptext = V.read(os.path.join(SOFT_POP, "common/decrees/zzz_MoG_SPA_greener_grass_decree.txt"))
    _, spbody = V.entry(sptext, "decree_greener_grass_campaign", "REPLACE:")

    hc_trigger = V.sub(hcbody, "state_trigger")
    sp_trigger = V.sub(spbody, "state_trigger")
    van_trigger = V.sub(vbody, "state_trigger")
    assert hc_trigger is not None and "usfp_homestead_act_modifier" in hc_trigger, \
        "HC's anti-stacking gate is gone from state_trigger -- re-check GR.4c"
    assert sp_trigger is not None and re.sub(r"\s+", " ", sp_trigger).strip() == \
        re.sub(r"\s+", " ", van_trigger).strip(), \
        "_grey_soft_pop now customizes state_trigger too -- re-check GR.4c, this merge assumes it's still vanilla's"

    merged = V.replace_sub(spbody, "state_trigger", hc_trigger)
    text = ("# base: _grey_soft_pop's REPLACE (its own migration-pull numbers and ai_weight redesign).\n"
            "# HC's state_trigger layer merged in: a gate against stacking Greener Grass with HC's own\n"
            "# Homestead Act / Gold Rush decrees. soft_pop's body never touches state_trigger (its copy\n"
            "# is verbatim vanilla), so HC's gate would otherwise be dropped silently.\n"
            "REPLACE_OR_CREATE:decree_greener_grass_campaign = {" + merged + "}")
    write("common/decrees/zz_greys_hc_greener_grass.txt", text,
          "carry HC's decree-stacking gate on top of soft_pop's decree redesign",
          "Both HC and _grey_soft_pop REPLACE this vanilla decree with full bodies. HC's only change "
          "from vanilla is one NOR gate added to state_trigger; soft_pop's is an unrelated rebalance "
          "of the migration-pull modifier and the AI-weight branches, restating state_trigger with "
          "vanilla's own content. Grey's loads later, so its full body wins and HC's gate is gone, "
          "with nothing in error.log.")


