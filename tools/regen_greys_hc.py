def build_montenegro():
    gob_path = os.path.join(GOB, "common/history/countries/mon - montenegro.txt")
    usu_path = os.path.join(USU, "common/history/countries/mon - montenegro.txt")
    gob_text = V.read(gob_path)
    usu_text = V.read(usu_path)

    assert "set_military_wage_level = low" in usu_text, \
        "USU's military-wage line is gone -- re-check GR.4d"
    assert "g:usu_logistics" in usu_text, \
        "USU no longer redirects the tariff good to g:usu_logistics -- re-check GR.4d"
    assert "goods = g:merchant_marine" in gob_text, \
        "GoB no longer names g:merchant_marine on this tariff line -- re-check GR.4d"

    merged = gob_text
    before = merged
    merged = merged.replace(
        "set_import_tariff_level = {\n\t\t\t\tgoods = g:merchant_marine",
        "set_import_tariff_level = { # USU -- Montenegro is landlocked, its Trade Center needs "
        "logistics, not Merchant Marine\n\t\t\t\tgoods = g:usu_logistics",
        1,
    )
    assert merged != before and "g:usu_logistics" in merged, \
        "GoB's import-tariff block indentation changed -- the merchant_marine substitution didn't match, re-check GR.4d"

    before = merged
    merged = merged.replace(
        "set_tax_level = very_low\n",
        "set_tax_level = very_low\n\t\t\tset_military_wage_level = low # USU\n",
        1,
    )
    assert merged != before, \
        "GoB's set_tax_level line changed -- the anchor for USU's wage line didn't match, re-check GR.4d"

    header = (
        "# Grey's x HC+GoB+MoH compatch (GR.4) -- reconcile the shared file path\n"
        "# common/history/countries/mon - montenegro.txt\n"
        "# Generated by tools/regen_greys_hc.py on " + DATE + ". Do not hand-edit: the next run\n"
        "# overwrites this file. Change the generator instead.\n"
        "#\n"
        "# grey_usu and Gates of Bosphorus both ship a file at this exact relative path. It is not\n"
        "# REPLACE:-prefixed -- this is a raw virtual-filesystem path collision, not a by-key merge:\n"
        "# whichever mod loads last provides the ONLY copy the game reads, the earlier one is\n"
        "# invisible, not merged. grey_usu (Grey's block) loads after the whole HC+GoB+MoH block, so\n"
        "# its 94-line body wins outright and GoB's 102-line body -- three new starting techs, a new\n"
        "# journal entry (je_balkfm_mon_prince_bishopric), GoB's own IP3 state-formation integration,\n"
        "# and an else-branch event (balkfm_montenegro.001/.019) -- never runs at all.\n"
        "#\n"
        "# Base here: GoB's body (vanilla is 93 lines, GoB's is the substantial, deliberate rework;\n"
        "# USU's 94-line delta from vanilla is one new line and one changed good). USU's own two\n"
        "# changes layered on top: landlocked Montenegro's first Trade Center tariff good redirected\n"
        "# from g:merchant_marine to USU's own g:usu_logistics, and set_military_wage_level = low\n"
        "# added after set_tax_level.\n\n"
    )
    text = header + merged.lstrip("﻿")
    write("common/history/countries/mon - montenegro.txt", text, raw=True)


