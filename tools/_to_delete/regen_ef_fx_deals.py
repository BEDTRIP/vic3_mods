def write_crisis(currencies):
    """Night 2, item 3 (2.10): E&F's currency crisis (money_value down 50% in half a year, or the CB
    bankrupt) makes every CB sell all of the currency -- and set the ISSUER's metal to 0 while the
    sellers get nothing: the metal left the game (run 18: Russia 125M -> 3.5M, 24.11-1.12.1836).
    Now the sellers redeem it: the issuer pays the holdings at its parity from its metal, as far as
    the metal goes (zz_ef_crisis_redeem, scripted_effects/zz_ef_money_model.txt)."""
    out = ["# GENERATED by tools/regen_ef_fx_deals.py -- do not edit by hand.\n"
           "# EF.48, night 2 item 3 (2.10): E&F's sell_<currency>_currency_crisis -- the sellers redeem the\n"
           "# currency for the issuer's metal (at most what it holds) instead of the issuer's metal set to 0.\n"
           "# !! MAINTENANCE !! Key-level REPLACE_OR_CREATE of E&F's effects: regenerate after an E&F update.\n\n"]
    for c in currencies:
        out.append(CRISIS.format(c=c))
    with open(OUT_CRISIS, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write("".join(out))
    print("ok", len(currencies), "crisis effects ->", OUT_CRISIS)


