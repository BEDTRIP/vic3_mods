    lines = ["# GENERATED by tools/regen_ef_fx_deals.py -- do not edit by hand.\n"
             "# EF.48, night 2 item 2 (2.10): E&F's currency stocks of a CB state in our money's scale,\n"
             "# the same factor as the metal (zz_ef_metal_rescale_step). STATE scope.\n"
             "zz_ef_fx_stock_rescale = {\n"]
    for c in currencies:
        for v in (f"stockpiling_{c}_state_1", f"stockpiling_{c}_reserve_currency_state_1"):
            lines.append(f"\tif = {{ limit = {{ has_variable = {v} }} "
                         f"change_variable = {{ name = {v} multiply = owner.var:zz_ef_metal_rescale }} }}\n")
    lines.append("}\n")
    with open(OUT_RESCALE, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write("".join(lines))
    print("ok", len(currencies), "currencies ->", OUT_RESCALE)


