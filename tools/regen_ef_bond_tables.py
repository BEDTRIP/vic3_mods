def main() -> int:
    text = sgui()
    assert text.count("{") == text.count("}")
    with open(OUT_SG, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write(text)
    sv = ("# GENERATED by tools/regen_ef_bond_tables.py -- do not edit by hand.\n" + SV)
    with open(os.path.join(HOTFIX, "common", "script_values", "zz_ef_bond_tables_values.txt"), "w",
              encoding="utf-8-sig", newline="\n") as f:
        f.write(sv)
    for lang in LANGS:
        d = LOC["russian" if lang == "russian" else "english"]
        lines = [f"l_{lang}:\n"] + [f' {k}:0 "{v.replace("¤", CUR)}"\n' for k, v in d.items()]
        p = os.path.join(HOTFIX, "localization", lang, f"zz_ef_bond_tables_l_{lang}.yml")
        with open(p, "w", encoding="utf-8-sig", newline="\n") as f:
            f.write("".join(lines))
    print("ok ->", OUT_SG)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
