#!/usr/bin/env python3
"""
Е.6 (5.10, Д.3) -- the bond tables in "Budget -> Finances": who holds our bonds and whose bonds we hold.

Why this exists
---------------
E&F's two blocks -- "Investments in foreign debt" (gold_lent_to_foreign_countries) and "Foreign gold lent
against our debt" (gold_lent_to_us) -- list only the human player's own purchases (seller_country_general_N,
total_bond_value_N); the bonds the AI buys for a country (ai_buy_bond_1..10: ai_seller_country_general_N,
ai_total_bond_value_N) and the private banks' bonds (ai_privat_bank_*_1..25) were in lists hidden by EF.30
(an E&F check failing every frame). The user (4.10) saw "one Portugal 4.40M" while Britain held ~20M of bonds.

What this does
--------------
A scripted GUI zz_ef_bonds_update (root = the player) fills two global lists of countries:
  zz_ef_bt_in_list  -- who holds OUR bonds: other countries' treasuries (their slots naming us as the seller)
                       and their private banks (bank slots whose seller list has us);
  zz_ef_bt_out_list -- whose bonds WE hold: the sellers of our treasury's slots and of our banks' slots.
Per row (variables on the listed country): treasury sum (engine money, as E&F's purchase price), its yearly
rate and interest a week; banks' sum (in gold -- E&F values the banks' bonds in gold), rate, interest a week.
regen_ef_cb_rate_gui.py puts a button and the two tables under E&F's headers.

Output: common/scripted_guis/zz_ef_bond_tables.txt, localization/*/zz_ef_bond_tables_l_*.yml.
"""
from __future__ import annotations

import os

HERE = os.path.dirname(os.path.abspath(__file__))
HOTFIX = os.path.normpath(os.path.join(HERE, r"..\_ef\ef hotfix 1.13"))
OUT_SG = os.path.join(HOTFIX, "common", "scripted_guis", "zz_ef_bond_tables.txt")
LANGS = ["english", "russian", "braz_por", "french", "german", "japanese",
         "korean", "polish", "simp_chinese", "spanish", "turkish"]
N_STATE = 10   # ai_buy_bond_1..10 and the player's slots 1..10
N_BANK = 25    # ai_privat_bank_*_1..25
VARS = ["zz_ef_bt_t_amt", "zz_ef_bt_t_week", "zz_ef_bt_b_amt", "zz_ef_bt_b_year",
        "zz_ef_bto_t_amt", "zz_ef_bto_t_week", "zz_ef_bto_b_amt", "zz_ef_bto_b_year"]  # in / out rows


def state_slot(n: int, seller: str) -> str:
    """Treasury slot n of the scope country (the holder) bought from `seller`: E&F's AI slot and the player's."""
    return (f"\t\t\tif = {{ limit = {{ has_variable = ai_buy_bond_{n}_on var:ai_buy_bond_{n}_on = 1 "
            f"has_variable = ai_seller_country_general_{n} var:ai_seller_country_general_{n} = {seller} "
            f"has_variable = ai_total_bond_value_{n} }}\n"
            f"\t\t\t\tchange_variable = {{ name = zz_ef_bt_t_amt add = var:ai_total_bond_value_{n} }}\n"
            f"\t\t\t\tchange_variable = {{ name = zz_ef_bt_t_week add = {{ value = var:ai_interest_per_month_calculated_{n} multiply = 0.25 }} }}\n"
            f"\t\t\t}}\n"
            f"\t\t\tif = {{ limit = {{ has_variable = total_bond_value_{n} var:total_bond_value_{n} > 0 "
            f"has_variable = seller_country_general_{n} var:seller_country_general_{n} = {seller} }}\n"
            f"\t\t\t\tchange_variable = {{ name = zz_ef_bt_t_amt add = var:total_bond_value_{n} }}\n"
            f"\t\t\t\tchange_variable = {{ name = zz_ef_bt_t_week add = {{ value = var:interest_per_month_calculated_{n} multiply = 0.25 }} }}\n"
            f"\t\t\t}}\n")


def sgui() -> str:
    out = ["# GENERATED by tools/regen_ef_bond_tables.py -- do not edit by hand.\n"
           "# Е.6 (5.10, Д.3): who holds our bonds (zz_ef_bt_in_list) and whose bonds we hold (zz_ef_bt_out_list).\n"
           "# Rows: variables on the listed country -- treasury sum (money), interest a week; banks' sum (gold), interest\n"
           "# a year (gold). Filled when the player opens the table (button in Budget -> Finances).\n"
           "zz_ef_bonds_update = {\n\teffect = {\n\t\tsave_scope_as = bt_root\n"
           "\t\tclear_global_variable_list = zz_ef_bt_in_list\n\t\tclear_global_variable_list = zz_ef_bt_out_list\n"
           "\t\tevery_country = {\n"]
    for v in VARS:
        out.append(f"\t\t\tset_variable = {{ name = {v} value = 0 }}\n")
    out.append("\t\t}\n")
    # 1. who holds ours
    out.append("\t\t# 1. other countries holding our bonds: their treasury slots naming us, their banks' slots with us\n"
               "\t\tevery_country = {\n\t\t\tlimit = { NOT = { this = scope:bt_root } }\n")
    for n in range(1, N_STATE + 1):
        out.append(state_slot(n, "scope:bt_root"))
    for m in range(1, N_BANK + 1):
        out.append(f"\t\t\tif = {{ limit = {{ has_variable = ai_privat_bank_bond_value_{m} var:ai_privat_bank_bond_value_{m} > 0 "
                   f"is_target_in_variable_list = {{ name = ai_privat_bank_seller_country_general_{m} target = scope:bt_root }} }}\n"
                   f"\t\t\t\tchange_variable = {{ name = zz_ef_bt_b_amt add = var:ai_privat_bank_bond_value_{m} }}\n"
                   f"\t\t\t\tif = {{ limit = {{ has_variable = ai_privat_bank_interest_calculated_{m} }} "
                   f"change_variable = {{ name = zz_ef_bt_b_year add = var:ai_privat_bank_interest_calculated_{m} }} }}\n"
                   f"\t\t\t}}\n")
    out.append("\t\t\tif = { limit = { OR = { var:zz_ef_bt_t_amt > 0 var:zz_ef_bt_b_amt > 0 } } "
               "add_to_global_variable_list = { name = zz_ef_bt_in_list target = this } }\n\t\t}\n")
    # 2. whose we hold: our slots, the sum goes on the seller (the listed country)
    out.append("\t\t# 2. our bonds of other countries: each of our slots adds to its seller's row\n")
    for n in range(1, N_STATE + 1):
        out.append(f"\t\tif = {{ limit = {{ has_variable = ai_buy_bond_{n}_on var:ai_buy_bond_{n}_on = 1 "
                   f"has_variable = ai_seller_country_general_{n} has_variable = ai_total_bond_value_{n} }}\n"
                   f"\t\t\tvar:ai_seller_country_general_{n} = {{\n"
                   f"\t\t\t\tchange_variable = {{ name = zz_ef_bto_t_amt add = scope:bt_root.var:ai_total_bond_value_{n} }}\n"
                   f"\t\t\t\tchange_variable = {{ name = zz_ef_bto_t_week add = {{ value = scope:bt_root.var:ai_interest_per_month_calculated_{n} multiply = 0.25 }} }}\n"
                   f"\t\t\t\tif = {{ limit = {{ NOT = {{ is_target_in_global_variable_list = {{ name = zz_ef_bt_out_list target = this }} }} }} add_to_global_variable_list = {{ name = zz_ef_bt_out_list target = this }} }}\n"
                   f"\t\t\t}}\n\t\t}}\n"
                   f"\t\tif = {{ limit = {{ has_variable = seller_country_general_{n} has_variable = total_bond_value_{n} var:total_bond_value_{n} > 0 }}\n"
                   f"\t\t\tvar:seller_country_general_{n} = {{\n"
                   f"\t\t\t\tchange_variable = {{ name = zz_ef_bto_t_amt add = scope:bt_root.var:total_bond_value_{n} }}\n"
                   f"\t\t\t\tchange_variable = {{ name = zz_ef_bto_t_week add = {{ value = scope:bt_root.var:interest_per_month_calculated_{n} multiply = 0.25 }} }}\n"
                   f"\t\t\t\tif = {{ limit = {{ NOT = {{ is_target_in_global_variable_list = {{ name = zz_ef_bt_out_list target = this }} }} }} add_to_global_variable_list = {{ name = zz_ef_bt_out_list target = this }} }}\n"
                   f"\t\t\t}}\n\t\t}}\n")
    for m in range(1, N_BANK + 1):
        out.append(f"\t\tif = {{ limit = {{ has_variable = ai_privat_bank_bond_value_{m} var:ai_privat_bank_bond_value_{m} > 0 }}\n"
                   f"\t\t\trandom_in_list = {{\n\t\t\t\tvariable = ai_privat_bank_seller_country_general_{m}\n"
                   f"\t\t\t\tchange_variable = {{ name = zz_ef_bto_b_amt add = scope:bt_root.var:ai_privat_bank_bond_value_{m} }}\n"
                   f"\t\t\t\tif = {{ limit = {{ scope:bt_root = {{ has_variable = ai_privat_bank_interest_calculated_{m} }} }} "
                   f"change_variable = {{ name = zz_ef_bto_b_year add = scope:bt_root.var:ai_privat_bank_interest_calculated_{m} }} }}\n"
                   f"\t\t\t\tif = {{ limit = {{ NOT = {{ is_target_in_global_variable_list = {{ name = zz_ef_bt_out_list target = this }} }} }} add_to_global_variable_list = {{ name = zz_ef_bt_out_list target = this }} }}\n"
                   f"\t\t\t}}\n\t\t}}\n")
    out.append("\t}\n}\n")
    return "".join(out)


