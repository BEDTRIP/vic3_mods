NEW_IN_113_MOD = {"country_max_unassigned_generals_add", "country_max_unassigned_admirals_add"}
# Dropped by TGR on purpose (GR.7a).
TGR_DROPS = {"country_loan_interest_rate_mult"}

FIELD = re.compile(r'(?m)^([ \t]*)([a-z_]+)[ \t]*=[ \t]*(-?[\d.]+|yes|no)[ \t]*(#[^\n]*)?$')

HEADER = """# TGR.1 -- country ranks: vanilla 1.13 bodies + TGR's own changes
# Generated by tools/regen_tgr_113_fix.py on {date}. Do not hand-edit: the next
# run overwrites this file. Change the generator instead.
#
# Load order: TGR -> ... -> THIS (megapack). With the Grey's pack,
# _greys/greys+tgr done loads later and re-issues these ranks on soft_pop's bodies.
# Why: TGR's REPLACE_OR_CREATE bodies predate 1.13 and silently drop
# treaty_article_cost, ai_pool_character_multiplier,
# ai_innovation_critical_threshold and country_max_unassigned_generals/admirals_add.
# TGR's own fields are kept (marked "# TGR"): country_construction_add, the lower
# independence support, the trade-advantage INJECT; rank-dependent loan interest
# stays out (decision 27.08.2026, GR.7a).
"""


def fields(block: str) -> dict[str, str]:
    """Depth-1 scalar fields of a `{ ... }` block (sub-blocks skipped)."""
    out, depth = {}, 0
    for line in block.split("\n"):
        code = line.split("#", 1)[0]
        if depth == 1:
            m = re.match(r'^\s*([a-z_]+)\s*=\s*(-?[\d.]+|yes|no)\s*$', code)
            if m:
                out[m.group(1)] = m.group(2)
        depth += code.count("{") - code.count("}")
    return out


def build() -> str:
    van_text = V.read(os.path.join(VAN, "common/country_ranks/00_country_ranks.txt"))
    pol_text = V.read(os.path.join(TGR, "common/country_ranks/TGR_POLITICS_country_ranks.txt"))
    trd_text = V.read(os.path.join(TGR, "common/country_ranks/TGR_TRADE_country_ranks.txt"))
    records = []
    for rank in RANKS:
        _, vbody = V.entry(van_text, rank, None)
        _, tbody = V.entry(pol_text, rank, "REPLACE_OR_CREATE:")

        # top level: TGR may only lack 1.13 additions, never differ
        vtop, ttop = fields("{" + vbody + "}"), fields("{" + tbody + "}")
        for k, v in vtop.items():
            if k not in ttop:
                assert k in NEW_IN_113_TOP, f"{rank}: TGR drops top-level {k} -- classify it"
            else:
                assert ttop[k] == v, f"{rank}: TGR changes top-level {k} {v}->{ttop[k]} -- classify it"
        for k in ttop:
            assert k in vtop, f"{rank}: TGR adds top-level {k} -- classify it"

        # sub-blocks other than modifier (valid_country_types, ...) are taken from
        # vanilla: TGR must not have changed them
        norm = lambda s: re.sub(r"\s+", " ", re.sub(r"#[^\n]*", "", s or "")).strip()
        for s in (set(V.sub_names(vbody)) | set(V.sub_names(tbody))) - {"modifier"}:
            assert norm(V.sub(vbody, s)) == norm(V.sub(tbody, s)), f"{rank}: TGR changes sub-block {s} -- classify it"

        vmod, tmod = V.sub(vbody, "modifier"), V.sub(tbody, "modifier")
        assert vmod is not None and tmod is not None, f"{rank}: no modifier block"
        vf, tf = fields(vmod), fields(tmod)
        new_mod = vmod
        for k in vf:
            if k in tf:
                continue
            if k in TGR_DROPS:
                new_mod = FIELD.sub(lambda m: (f"{m.group(1)}# {m.group(2)} = {m.group(3)}  # dropped by TGR's loan system (GR.7a)"
                                               if m.group(2) == k else m.group(0)), new_mod)
            else:
                assert k in NEW_IN_113_MOD, f"{rank}: TGR drops modifier {k} -- classify it"
        extra = []
        for k, tv in tf.items():
            if k not in vf:
                extra.append(f"{k} = {tv}  # TGR, not in vanilla")
            elif vf[k] != tv:
                new_mod = FIELD.sub(lambda m: (f"{m.group(1)}{k} = {tv}  # TGR (vanilla {vf[k]})"
                                               if m.group(2) == k else m.group(0)), new_mod)
        try:
            _, ibody = V.entry(trd_text, rank, "INJECT:")
            imod = V.sub(ibody, "modifier")
            for k, v in fields(imod).items():
                assert k not in vf and k not in tf, f"{rank}: TGR_TRADE injects {k} over an existing field"
                extra.append(f"{k} = {v}  # TGR_TRADE inject")
        except KeyError:
            pass
        if extra:
            close = new_mod.rstrip().rfind("}")
            new_mod = new_mod[:close].rstrip() + "\n\t\t" + "\n\t\t".join(extra) + "\n\t}"
        new_body = V.replace_sub(vbody, "modifier", new_mod)
        records.append(f"REPLACE_OR_CREATE:{rank} = {{{new_body}}}")
    return HEADER.format(date=DATE) + "\n" + "\n\n".join(records) + "\n"


