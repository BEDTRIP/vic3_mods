def _find(root: str, cat: str, key: str, prefixes=None) -> list[str]:
    out = []
    for dp, dn, fn in os.walk(os.path.join(root, "common", cat)):
        for f in sorted(fn):
            if not f.endswith(".txt"):
                continue
            text = V.read(os.path.join(dp, f))
            for m in re.finditer(r"(?m)^((?:[A-Z_]+:)?)" + re.escape(key) + r"\s*=\s*\{", text):
                if prefixes is not None and m.group(1) not in prefixes:
                    continue
                i = text.index("{", m.start())
                j = V._match_brace(text, i)
                out.append(text[i + 1:j])
    return out


def _field(body: str, name: str) -> str | None:
    """The whole depth-0 statement `name = ...` of a body, or None."""
    span = V.sub_span(body, name)
    if span:
        return body[span[0]:span[1]].strip()
    depth = 0
    for line in body.split("\n"):
        code = line.split("#", 1)[0]
        if depth == 0:
            m = re.match(r"^\s*(" + re.escape(name) + r"\s*=\s*\S+)\s*$", code)
            if m:
                return m.group(1)
        depth += code.count("{") - code.count("}")
    return None


def build_injects() -> dict[str, str]:
    per_cat: dict[str, list[str]] = {}
    for cat, key, fields in INJECTS:
        van = _find(VAN, cat, key)
        assert len(van) == 1, f"{cat}/{key}: {len(van)} vanilla bodies -- re-check"
        tgr = _find(TGR, cat, key, prefixes=("", "REPLACE:", "REPLACE_OR_CREATE:"))
        assert tgr, f"{cat}/{key}: TGR no longer re-issues it -- drop it from INJECTS"
        stmts = []
        for fld in fields:
            v = _field(van[0], fld)
            assert v, f"{cat}/{key}: vanilla has no {fld} -- re-check"
            for b in tgr:
                assert _field(b, fld) is None, f"{cat}/{key}: TGR now has {fld} -- drop it from INJECTS"
            stmts.append(v)
        per_cat.setdefault(cat, []).append(
            f"INJECT:{key} = {{\n\t" + "\n\t".join(s.replace("\n", "\n\t") for s in stmts) + "\n}")
    return {f"common/{cat}/zz_tgr_113_fields.txt": INJECT_HEADER.format(date=DATE) + "\n" + "\n\n".join(recs) + "\n"
            for cat, recs in per_cat.items()}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files = {REL: build()}
    files.update(build_injects())
    targets = [OUT] + MEGAPACKS
    drift = []
    for root in targets:
      for rel, text in files.items():
        assert V.brace_balance(text) == 0, rel
        blob = text.encode("utf-8")
        p = os.path.join(root, rel)
        old = open(p, "rb").read() if os.path.isfile(p) else None
        if old != blob:
            drift.append(p)
            if not a.check:
                os.makedirs(os.path.dirname(p), exist_ok=True)
                open(p, "wb").write(blob)
                print(f"  wrote {p}")
    if a.check:
        for p in drift:
            print(f"  DRIFT {p}")
        print("all files match the current vanilla / TGR sources" if not drift else f"{len(drift)} file(s) drifted")
        return 1 if drift else 0
    print(f"  {len(files)} files x {len(targets)} places, {len(drift)} written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
