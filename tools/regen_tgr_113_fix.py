#!/usr/bin/env python3
"""
TGR.1 + TGR.3 -- TGR records written before game 1.13, brought up to 1.13.

TGR re-issues many vanilla records with full bodies written against an older
vanilla. Fields game 1.13 added to those records silently disappear. Two parts:

  1. Country ranks (TGR.1) -- full re-issue, see below.
  2. Plain 1.13 fields TGR's bodies lack (TGR.3), put back with INJECT:
     (adds fields, wipes nothing), each read from vanilla 1.13:
       treaty_articles  military_assistance, foreign_investment_rights --
                        max_target_involvement / target_involvement_applies_to
                        (the involvement cap), military_assistance's
                        non_fulfillment;
       company_types    category (1.13 company categories) on four companies,
                        prestige_goods_trigger on five;
       goods            obsession_chance on fish and groceries;
       buildings        aliases on nine industry buildings (save compatibility).
     Everything else the scan finds (TGR's laws, taxation, journal entries,
     GER formation, trade-center and refrigeration methods) is TGR's own
     redesign or shadowed by a later mod -- classified in the plan (TGR.3).

Country ranks
-------------
TGR's `common/country_ranks/TGR_POLITICS_country_ranks.txt` REPLACE_OR_CREATEs all
eight ranks with bodies written against an older vanilla. Game 1.13 added fields
to those records that TGR's bodies simply do not have:

    top level   treaty_article_cost, ai_pool_character_multiplier,
                ai_innovation_critical_threshold
    modifier    country_max_unassigned_generals_add,
                country_max_unassigned_admirals_add

so under TGR every rank loses them silently. With the Grey's pack this repairs
itself (soft_pop re-issues 1.13 bodies, `_greys/greys+tgr done` puts TGR's fields
back on top); without Grey's nothing did, until this file.

What is TGR's and is kept
-------------------------
Read live from TGR's files, never hand-copied:
  * every modifier field TGR adds or sets to a different value than vanilla
    1.13 -- today country_construction_add (+30 great, +20 major) and the
    lower country_support_independence_weekly_liberty_desire_add;
  * TGR_TRADE_country_ranks.txt's INJECT of state_export_advantage_mult /
    state_import_advantage_mult -- a REPLACE_OR_CREATE loading after TGR would
    otherwise wipe it;
  * country_loan_interest_rate_mult stays OUT: decision 27.08.2026 (GR.7a),
    TGR's loan system drops rank-dependent interest on purpose.

Anything else TGR drops from a vanilla body makes the generator stop -- a new
difference must be classified by a human (1.13 addition or TGR's intent).

Output: `_tgr/tgr 1.13 fix done/common/country_ranks/zz_tgr_ranks_fix.txt` and
`common/<category>/zz_tgr_113_fields.txt`, copied into the megapacks that carry
TGR (`megapack`, `megapack no t&r`). With the Grey's pack, grey_diplo re-issues
foreign_investment_rights later -- `_greys/greys_kai_fix done` carries the same
two fields there.

Usage:
    py tools/regen_tgr_113_fix.py            # write
    py tools/regen_tgr_113_fix.py --check    # report only, exit 1 if sources drifted
"""

